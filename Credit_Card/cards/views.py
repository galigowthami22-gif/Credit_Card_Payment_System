import re
from datetime import date

from django.shortcuts import get_object_or_404, render, redirect
from django.contrib.auth.decorators import login_required
from django.contrib import messages
from django.conf import settings
from django.views.decorators.http import require_POST
from decimal import Decimal, InvalidOperation
import httpx
import logging
from .models import Card
from users.tokens import create_payment_authorization_token

logger = logging.getLogger(__name__)


def _valid_card_number(value):
    number = re.sub(r'[\s-]', '', value or '')
    if not re.fullmatch(r'[0-9]{12,19}', number):
        return None
    checksum = 0
    for index, digit in enumerate(reversed(number)):
        digit_value = int(digit)
        if index % 2:
            digit_value *= 2
            if digit_value > 9:
                digit_value -= 9
        checksum += digit_value
    return number if checksum % 10 == 0 else None


def _valid_expiry(value):
    if not re.fullmatch(r'(0[1-9]|1[0-2])/[0-9]{2}', value or ''):
        return False
    month, short_year = (int(part) for part in value.split('/'))
    return (2000 + short_year, month) >= (date.today().year, date.today().month)


@login_required
def dashboard(request):
    user_cards = Card.objects.filter(user=request.user)
    return render(request, 'cards/dashboard.html', {'cards': user_cards})

@login_required
def card_list(request):
    user_cards = Card.objects.filter(user=request.user)
    return render(request, 'cards/card_list.html', {'cards': user_cards})

@login_required
def add_card(request):
    if request.method == 'POST':
        name = request.POST.get('card_holder_name', '').strip()
        number = _valid_card_number(request.POST.get('card_number', ''))
        expiry = request.POST.get('expiry_date', '')
        if not name or len(name) > 255 or number is None or not _valid_expiry(expiry):
            messages.error(request, 'Enter a valid cardholder name, card number, and future expiry date.')
            return redirect('add_card')

        last_4 = number[-4:]
        masked_number = "**** **** **** " + last_4
        Card.objects.create(
            user=request.user,
            card_holder_name=name,
            masked_card_number=masked_number,
            last_four_digits=last_4,
            expiry_date=expiry,
        )
        return redirect('card_list')

    return render(request, 'cards/add_card.html')

@login_required
def edit_card(request, card_id):
    card = get_object_or_404(Card, id=card_id, user=request.user)
    
    if request.method == 'POST':
        name = request.POST.get('card_holder_name', '').strip()
        expiry = request.POST.get('expiry_date', '')
        if not name or len(name) > 255 or not _valid_expiry(expiry):
            messages.error(request, 'Enter a valid cardholder name and future expiry date.')
            return redirect('edit_card', card_id=card.pk)
        card.card_holder_name = name
        card.expiry_date = expiry
        card.save()
        return redirect('card_list')
        
    return render(request, 'cards/edit_card.html', {'card': card})

@login_required
@require_POST
def delete_card(request, card_id):
    card = get_object_or_404(Card, id=card_id, user=request.user)
    card.delete()
    return redirect('card_list')


@login_required
@require_POST
def make_payment(request, payment_reference):
    card = Card.objects.filter(
        payment_reference=payment_reference,
        user=request.user,
    ).first()
    if card is None:
        messages.error(request, 'Saved card not found.')
        return redirect('card_list')

    try:
        amount = Decimal(request.POST.get('amount', ''))
    except InvalidOperation:
        messages.error(request, 'Enter a valid payment amount.')
        return redirect('card_list')

    if not amount.is_finite() or amount <= 0:
        messages.error(request, 'Payment amount must be greater than zero.')
        return redirect('card_list')

    try:
        response = httpx.post(
            settings.PAYMENT_API_URL,
            json={
                'payment_reference': str(card.payment_reference),
                'amount': str(amount),
            },
            headers={
                'Authorization': (
                    f'Bearer {create_payment_authorization_token(request.user.pk, card)}'
                ),
            },
            timeout=10.0,
        )
    except httpx.RequestError:
        logger.exception('Could not reach the FastAPI payment service.')
        messages.error(
            request,
            'Payment service is unavailable. Start the FastAPI server and try again.',
        )
        return redirect('card_list')

    if response.status_code == 401:
        logger.warning('FastAPI rejected the payment token generated by CardFlow.')
        messages.error(
            request,
            'FastAPI could not authenticate this payment. Check that JWT_SECRET_KEY '
            'and JWT_ALGORITHM match in both services, then restart both services.',
        )
        return redirect('card_list')

    if response.is_error:
        try:
            error_body = response.json()
        except ValueError:
            error_body = {}
        detail = error_body.get('detail') if isinstance(error_body, dict) else None
        messages.error(request, detail or 'Payment could not be processed.')
        return redirect('card_list')

    try:
        payment = response.json()
    except ValueError:
        logger.error('FastAPI returned an invalid payment response.')
        messages.error(request, 'Payment service returned an invalid response.')
        return redirect('card_list')
    if not isinstance(payment, dict) or not {'transaction_id', 'status'} <= payment.keys():
        logger.error('FastAPI returned an incomplete payment response.')
        messages.error(request, 'Payment service returned an invalid response.')
        return redirect('card_list')

    messages.success(
        request,
        f"Payment {payment['transaction_id']} finished with status "
        f"{payment['status']}.",
    )
    return redirect('transaction-history-page')
